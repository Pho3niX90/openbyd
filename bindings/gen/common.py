"""What the emitters share: an indenting writer and help with documentation."""

from __future__ import annotations

import re
import textwrap
from collections.abc import Iterable

from gen.ir import Surface, Type


class Writer:
    """Collects lines of source code at the current indentation."""

    def __init__(self, indent: str = "    ") -> None:
        self._lines: list[str] = []
        self._indent = indent
        self._level = 0

    def line(self, text: str = "") -> None:
        self._lines.append(self._indent * self._level + text if text else "")

    def lines(self, lines: Iterable[str]) -> None:
        for text in lines:
            self.line(text)

    def blank(self) -> None:
        """An empty line, unless the last line is one already or opens a block."""
        if self._lines and self._lines[-1].strip() and not self._lines[-1].rstrip().endswith(("{", "(")):
            self._lines.append("")

    def indent(self) -> None:
        self._level += 1

    def dedent(self) -> None:
        self._level -= 1
        # No empty line before a closing brace.
        while self._lines and not self._lines[-1].strip():
            self._lines.pop()

    def text(self) -> str:
        return "\n".join(self._lines).rstrip() + "\n"


def wrap(text: str, width: int = 96) -> list[str]:
    """Prose as lines no longer than ``width``."""
    return textwrap.wrap(text, width, break_long_words=False, break_on_hyphens=False) or [""]


def code_spans(text: str, replace: str) -> str:
    """Rewrites every `code` span of ``text`` with ``replace``, a ``re.sub`` template."""
    return re.sub(r"`([^`]+)`", replace, text)


def header(surface: Surface, comment: str = "//") -> list[str]:
    """The lines that open every generated file."""
    return [
        f"{comment} Generated by bindings/generate.py from bindings/spec.py and pyBYD",
        f"{comment} {surface.pybyd_commit}. Do not edit: change the spec and run the generator.",
    ]


def default_text(value: object) -> str:
    """A default as documentation shows it."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return f'"{value}"'
    return str(value)


def has_float(surface: Surface, kind: Type, seen: frozenset[str] = frozenset()) -> bool:
    """Whether a value of ``kind`` holds a float anywhere inside it."""
    if kind.kind == "float":
        return True
    if kind.kind == "ref":
        struct = surface.structs.get(kind.name)
        if struct is None or kind.name in seen:
            return False
        return any(has_float(surface, item.type, seen | {kind.name}) for item in struct.fields)
    return any(has_float(surface, inner, seen) for inner in kind.of)
